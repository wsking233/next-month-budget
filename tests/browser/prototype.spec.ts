import { expect, test } from '@playwright/test';

for (const width of [375, 768, 1440]) {
  test(`${width}px 演示拆分、核对、记录与刷新隔离`, async ({ page }) => {
    await page.setViewportSize({ width, height: 900 });
    const errors: string[] = [];
    page.on('pageerror', error => errors.push(error.message));
    await page.goto('./#/');
    await expect(page.getByText('交互演示 · 不是真实账本')).toBeVisible();
    await expect(page.getByText('还没有预算周期')).toBeVisible();
    await page.getByRole('button', { name: '加载演示数据' }).click();
    const nav = page.getByRole('navigation', { name: '主导航' });
    for (const title of ['资金池', '账单', '预算计划', '历史记录', '设置', '概览']) {
      await nav.getByRole('link', { name: title, exact: true }).click();
      expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBeTruthy();
      await page.screenshot({ path: `test-results/prototype-${width}-${title}.png`, fullPage: true });
    }
    await nav.getByRole('link', { name: '账单', exact: true }).click();
    await page.getByRole('button', { name: '拆分核对' }).first().click();
    const dialog = page.getByRole('dialog');
    await expect(dialog).toBeVisible();
    await page.keyboard.press('Escape');
    await expect(dialog).not.toBeVisible();
    await expect(page.getByRole('button', { name: '拆分核对' }).first()).toBeFocused();
    await page.getByRole('button', { name: '拆分核对' }).first().click();
    await page.getByLabel('分配金额 1（元）').fill('2000.001');
    await expect(page.getByRole('button', { name: '核对分配', exact: true })).toBeDisabled();
    await page.getByLabel('分配金额 1（元）').fill('2000.01');
    await page.getByRole('button', { name: '添加分配行' }).click();
    await page.getByLabel('资金池 2', { exact: true }).selectOption('travel');
    await page.getByLabel('归属周期 2', { exact: true }).selectOption('nov');
    await page.getByLabel('分配金额 2（元）').fill('599.98');
    await expect(page.getByRole('button', { name: '核对分配', exact: true })).toBeDisabled();
    await page.getByLabel('分配金额 2（元）').fill('599.99');
    expect(await dialog.evaluate(el => el.scrollWidth <= el.clientWidth)).toBeTruthy();
    await page.getByRole('button', { name: '核对分配', exact: true }).click();
    await expect(page.getByRole('status')).toContainText('还款状态不变');
    await page.screenshot({ path: `test-results/allocation-${width}.png`, fullPage: true });
    await page.getByRole('button', { name: '确认模拟结算' }).click();
    await expect(dialog).not.toBeVisible();
    await expect(page.getByRole('article').getByText('演示已结算', { exact: true })).toBeVisible();
    await nav.getByRole('link', { name: '历史记录', exact: true }).click();
    await page.getByLabel('操作类型').selectOption('结算');
    await expect(page.getByText(/演示信用卡 A · DEMO-2026-10-A/).filter({ visible: true })).toBeVisible();
    await page.getByLabel('搜索记录').fill('不存在');
    await expect(page.getByText('暂时没有匹配的记录')).toBeVisible();
    await page.getByRole('button', { name: '清空演示', exact: true }).click();
    await page.getByRole('button', { name: '取消', exact: true }).click();
    await page.reload();
    await page.getByLabel('操作类型').selectOption('全部');
    await expect(page.getByText('暂时没有匹配的记录')).toBeVisible();
    expect(errors).toEqual([]);
  });
}

test('从空状态创建周期、资金池、拨款和账单，不自动拨款并保留错误输入', async ({ page }) => {
  await page.goto('./#/plans');
  await page.getByRole('button', { name: '创建预算周期', exact: true }).first().click();
  await page.getByLabel('周期名称').fill('验收周期');
  await page.getByLabel('开始日期').fill('2026-10-10');
  await page.getByLabel('结束日期').fill('2026-11-09');
  await page.getByRole('button', { name: '添加到演示', exact: true }).click();
  await expect(page.getByText('¥0.00', { exact: true })).toBeVisible();
  const nav = page.getByRole('navigation', { name: '主导航' });
  await nav.getByRole('link', { name: '资金池', exact: true }).click();
  await page.getByRole('button', { name: '创建资金池', exact: true }).first().click();
  await page.getByLabel('资金池名称').fill('学习');
  await page.getByRole('button', { name: '添加到演示', exact: true }).click();
  const pool = page.getByRole('article').filter({ has: page.getByRole('heading', { name: '学习', exact: true }) });
  await expect(pool.getByText('¥0.00', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: '模拟拨款', exact: true }).click();
  await page.getByLabel('资金池', { exact: true }).selectOption({ label: '学习' });
  await page.getByLabel('金额（元）', { exact: true }).fill('100.001');
  await page.getByRole('button', { name: '确认模拟拨款' }).click();
  await expect(page.getByRole('alert')).toBeVisible();
  await expect(page.getByLabel('金额（元）', { exact: true })).toHaveValue('100.001');
  await page.getByLabel('金额（元）', { exact: true }).fill('100.01');
  await page.getByRole('button', { name: '确认模拟拨款' }).click();
  await expect(pool.getByText('¥100.01', { exact: true })).toBeVisible();
  await nav.getByRole('link', { name: '账单', exact: true }).click();
  await page.getByRole('button', { name: '登记账单', exact: true }).click();
  await page.getByLabel('账户名称').fill('演示卡');
  await page.getByLabel('账单标识').fill('TEST-001');
  await page.getByLabel('账单日', { exact: true }).fill('2026-10-17');
  await page.getByLabel('还款日', { exact: true }).fill('2026-10-25');
  await page.getByLabel('金额（元）', { exact: true }).fill('120.01');
  await page.getByRole('button', { name: '添加到演示', exact: true }).click();
  await page.getByRole('button', { name: '拆分核对' }).click();
  await page.getByLabel('分配金额 1（元）').fill('120.01');
  await page.getByRole('button', { name: '核对分配', exact: true }).click();
  await page.getByRole('button', { name: '确认模拟结算' }).click();
  await nav.getByRole('link', { name: '资金池', exact: true }).click();
  await expect(pool.getByText('-¥20.00', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: '清空演示', exact: true }).click();
  await page.getByRole('button', { name: '确认替换演示' }).click();
  await expect(page.getByText('给生活留一个预算空间')).toBeVisible();
});
